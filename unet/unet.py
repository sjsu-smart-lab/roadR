import os
from concurrent.futures import ThreadPoolExecutor

json_path = '/content/drive/My Drive/RGB_Dec20_Road-r-mydrive/road_trainval_v1.0.json'

image_folder = '/content/drive/Shareddrives/Road_R_Dataset/ROAD-R-2023-Challenge-main/road/rgb-images/2015-03-03-11-31-36_stereo_centre_01/'

