with open(json_path) as f:
    annotations = json.load(f)

img_cache = {}

def resize_image(img, target_height=256, target_width=256):
    return cv2.resize(img, (target_width, target_height))

def create_mask(image_name, annotations):
    if image_name not in img_cache:
        img_path = os.path.join(image_folder, image_name)
        img = cv2.imread(img_path)
       
        img_cache[image_name] = img
    else:
        img = img_cache[image_name]

    height, width = img.shape[:2]
    mask = np.zeros((height, width), dtype=np.uint8)

    for annotation in annotations.get(image_name, []):
        points = np.array(annotation['polygon'], dtype=np.int32)

        cv2.fillPoly(mask, [points], 255)

    return mask

def process_image(image_name):
    if image_name.endswith('.jpg') and image_name in annotations:
        mask = create_mask(image_name, annotations)
        mask_path = os.path.join(mask_dir, f"mask_{image_name}")
        cv2.imwrite(mask_path, mask)

with ThreadPoolExecutor() as executor:
    executor.map(process_image, os.listdir(image_folder))

print(f"Generated masks are saved in {mask_dir}")

